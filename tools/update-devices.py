#!/usr/bin/env python3
"""Sync watch/manifest.xml products and docs/devices.md with the fēnix and MARQ
devices installed by the Connect IQ SDK Manager."""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEVICES = os.path.expanduser("~/Library/Application Support/Garmin/ConnectIQ/Devices")
FAMILIES = ("fenix", "marq")
MIN_CIQ = (3, 1, 0)  # manifest minApiLevel: background service with web requests

def main():
    rows, ids, skipped = [], [], []
    for i in sorted(d for d in os.listdir(DEVICES) if d.startswith(FAMILIES)):
        c = json.load(open(os.path.join(DEVICES, i, "compiler.json")))
        vers = [p.get("connectIQVersion", "0") for p in c.get("partNumbers", [])]
        best = max((tuple(int(x) for x in v.split(".")) for v in vers), default=(0,))
        if best < MIN_CIQ:
            skipped.append(i)
            continue
        ids.append(i)
        res = c.get("resolution", {})
        ver = max((p.get("connectIQVersion", "") for p in c.get("partNumbers", [])), default="")
        glance = any(a.get("type") == "glance" for a in c.get("appTypes", []))
        rows.append((i, c.get("displayName", i), f'{res.get("width")}×{res.get("height")}',
                     c.get("deviceFamily", ""), c.get("displayType", ""), ver, "yes" if glance else "no"))
    path = os.path.join(ROOT, "watch", "manifest.xml")
    m = open(path).read()
    block = "".join(f'            <iq:product id="{i}"/>\n' for i in ids)
    m = re.sub(r"(<!-- products:begin[^>]*-->\n).*?(\s*<!-- products:end -->)",
               lambda x: x.group(1) + block + x.group(2).lstrip("\n"), m, flags=re.S)
    open(path, "w").write(m)
    md = ["# Supported devices", "", "Generated by `tools/update-devices.py` from the SDK Manager device files.", "",
          "| id | model | screen | family | display | Connect IQ | glance |", "|---|---|---|---|---|---|---|"]
    md += ["| " + " | ".join(r) + " |" for r in rows]
    open(os.path.join(ROOT, "docs", "devices.md"), "w").write("\n".join(md) + "\n")
    if not ids:
        sys.exit("no fenix/marq devices with Connect IQ >= 3.1 installed")
    print(f"{len(ids)} devices: {' '.join(ids)}")
    if skipped:
        print(f"skipped (Connect IQ < 3.1): {' '.join(skipped)}")

if __name__ == "__main__":
    main()
